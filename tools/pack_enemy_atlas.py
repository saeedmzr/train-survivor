#!/usr/bin/env python3
"""Pack the extracted enemy sprites into a Unity atlas + generated sprite table.

Reads   art-work/enemies/<id>/sprite.png  (from tools/extract_enemy_art.py)
Writes  unity/Assets/_Project/Art/Resources/Art/atlas_enemies.png
        unity/Assets/_Project/Art/Resources/Art/Enemies/<id>.png   (normalised, for UGUI)
        unity/Assets/_Project/Scripts/Game/View/EnemyArt.Generated.cs
        art-work/enemies/_unity.json                                (id -> sprite + scale)

Sprites are normalised so every enemy has the same pixel height (PIX_H); the in-game
height comes from HEIGHT_M per enemy, so a Crawler really is shorter than a Tank.
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "art-work/enemies")
UNITY = os.path.join(ROOT, "unity/Assets/_Project")
ATLAS_DIR = os.path.join(UNITY, "Art/Resources/Art")
CS = os.path.join(UNITY, "Scripts/Game/View/EnemyArt.Generated.cs")

PIX_H = 160          # sprite height inside the atlas (72 sprites: 12 species x 6 frames)
PAD = 2
ATLAS = 2048

# world height in metres — the design scale for the billboard system
HEIGHT_M = {
    "walker": 2.0, "sprinter": 1.9, "tank": 2.9, "crawler": 1.15, "bloater": 2.1,
    "spitter": 1.8, "shrieker": 1.75, "bulwark": 2.3, "glider": 1.6, "drillmaw": 1.5,
    "lantern": 2.2, "rimback": 2.4,
}
# the id used by the game data (art-work uses "rimback", the roster says "rimeback")
GAME_ID = {"rimback": "rimeback"}


def shelf_pack(items, size):
    """items: [(name, image)] -> placements [(name, x, y, w, h)] or None if it fits badly."""
    x = y = 0
    row_h = 0
    out = []
    for name, im in items:
        w, h = im.size
        if w + PAD * 2 > size:
            return None
        if x + w + PAD * 2 > size:
            x = 0
            y += row_h + PAD * 2
            row_h = 0
        if y + h + PAD * 2 > size:
            return None
        out.append((name, x + PAD, y + PAD, w, h))
        x += w + PAD * 2
        row_h = max(row_h, h)
    return out


def main():
    ids = [d for d in sorted(os.listdir(ART)) if os.path.isdir(os.path.join(ART, d))]
    sprites = []
    for eid in ids:
        p = os.path.join(ART, eid, "sprite.png")
        if not os.path.exists(p):
            print("skip (no sprite):", eid)
            continue

        # the six walk frames (tools/make_enemy_walk.py); frame 0 is what icons/prefabs use
        frames = []
        for t in range(6):
            fp = os.path.join(ART, eid, "walk_%d.png" % t)
            if os.path.exists(fp):
                frames.append(Image.open(fp).convert("RGBA"))
        if not frames:
            frames = [Image.open(p).convert("RGBA")]

        for t, im in enumerate(frames):
            w = max(1, round(im.size[0] * PIX_H / im.size[1]))
            name = eid if t == 0 else "%s_f%d" % (eid, t)
            sprites.append((name, im.resize((w, PIX_H), Image.LANCZOS)))

    sprites.sort(key=lambda s: -s[1].size[0])
    place = None
    size = 512
    while place is None:
        size *= 2
        place = shelf_pack(sprites, size)

    atlas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    os.makedirs(os.path.join(ATLAS_DIR, "Enemies"), exist_ok=True)
    for (name, im), (_, x, y, w, h) in zip(sprites, place):
        atlas.paste(im, (x, y), im)
        im.save(os.path.join(ATLAS_DIR, "Enemies", name + ".png"))

    atlas_path = os.path.join(ATLAS_DIR, "atlas_enemies.png")
    atlas.save(atlas_path)

    rows = []
    unity = {}
    for (name, im), (_, x, y, w, h) in zip(sprites, place):
        sprite = "en_" + name
        rows.append('            new ArtAtlas.Entry { Name = "%s", Atlas = "enemies", X = %d, Y = %d, W = %d, H = %d, '
                    'AtlasW = %d, AtlasH = %d, Pivot = new Vector2(0.5f, 0f) },'
                    % (sprite, x, y, w, h, size, size))
        base = name.split("_f")[0]
        if name == base:   # frame 0: the record other tools read
            unity[name] = {"id": GAME_ID.get(name, name), "sprite": sprite, "heightM": HEIGHT_M.get(name, 2.0),
                           "px": [w, h], "source": "art-work/enemies/%s/walk_0.png" % name,
                           "frames": [sprite] + ["en_%s_f%d" % (name, t) for t in range(1, 6)]}

    cs = """// <auto-generated>
//   generated by tools/pack_enemy_atlas.py from art-work/enemies/*/sprite.png
//   do not edit: rerun the tool instead.
// </auto-generated>
using UnityEngine;

namespace TrainSurvivor.Game.View
{
    /// <summary>Enemy sprites packed into Resources/Art/atlas_enemies.png.</summary>
    public static class EnemyArt
    {
        public const int AtlasSize = %d;

        /// <summary>Entries shaped exactly like ArtAtlas.Entry so ArtSprites can merge them.</summary>
        public static readonly ArtAtlas.Entry[] Entries =
        {
%s
        };
    }
}
""" % (size, "\n".join(rows))
    open(CS, "w").write(cs)

    json.dump({"atlas": os.path.relpath(atlas_path, ROOT), "atlasSize": size, "sprites": unity},
              open(os.path.join(ART, "_unity.json"), "w"), indent=1)
    print("atlas %dx%d, %d sprites -> %s" % (size, size, len(sprites), os.path.relpath(atlas_path, ROOT)))
    print("table ->", os.path.relpath(CS, ROOT))


if __name__ == "__main__":
    main()
