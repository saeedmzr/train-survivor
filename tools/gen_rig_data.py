#!/usr/bin/env python3
"""Turn each art-work/enemies/<id>/rig.json into a C# table the rig builder reads.

    art-work/enemies/<id>/rig.json  ->  unity/.../Scripts/Game/View/EnemyRigData.Generated.cs

Only the joint skeleton and the gait parameters cross over; the mesh, the weights and
the bind poses are all computed in Unity from this, so the JSON stays the single authored
source. Re-run after editing a rig:

    python tools/gen_rig_data.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "art-work/enemies")
OUT = os.path.join(ROOT, "unity/Assets/_Project/Scripts/Game/View/EnemyRigData.Generated.cs")

ORDER = ["walker", "sprinter", "tank", "crawler", "bloater", "spitter",
         "shrieker", "bulwark", "glider", "drillmaw", "lantern", "rimback"]


def ident(name):
    return name[0].upper() + name[1:]


def load():
    rigs = []
    for name in ORDER:
        path = os.path.join(ART, name, "rig.json")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as fh:
            rigs.append(json.load(fh))
    return rigs


def emit(rigs):
    L = []
    L.append("// <auto-generated>")
    L.append("//   generated by tools/gen_rig_data.py from art-work/enemies/*/rig.json")
    L.append("//   do not edit: rerun the tool instead.")
    L.append("// </auto-generated>")
    L.append("namespace TrainSurvivor.Game.View")
    L.append("{")
    L.append("    /// <summary>Joint skeletons + gait parameters per species (authored in rig.json).</summary>")
    L.append("    public static class EnemyRigData")
    L.append("    {")
    L.append("        public struct Joint")
    L.append("        {")
    L.append("            public string Name;")
    L.append("            public int Parent;      // -1 = root")
    L.append("            public float X, Y;      // normalised sprite space, origin bottom-left")
    L.append("        }")
    L.append("")
    L.append("        public struct Gait")
    L.append("        {")
    L.append("            public float BobM, SwayM, RootTiltDeg, SpineDeg, ChestDeg;")
    L.append("            public float HeadDeg, HeadLag, ArmSwingDeg, ElbowDeg, HipDeg, KneeDeg, Asymmetry;")
    L.append("        }")
    L.append("")
    L.append("        public sealed class Rig")
    L.append("        {")
    L.append("            public string Id;")
    L.append("            public string Sprite;")
    L.append("            public float HeightM;")
    L.append("            public Joint[] Joints;")
    L.append("            public Gait Gait;")
    L.append("        }")
    L.append("")
    L.append("        static Gait G(float bob, float sway, float tilt, float spine, float chest,")
    L.append("                      float head, float lag, float arm, float elbow, float hip,")
    L.append("                      float knee, float asym)")
    L.append("        {")
    L.append("            return new Gait")
    L.append("            {")
    L.append("                BobM = bob, SwayM = sway, RootTiltDeg = tilt, SpineDeg = spine, ChestDeg = chest,")
    L.append("                HeadDeg = head, HeadLag = lag, ArmSwingDeg = arm, ElbowDeg = elbow,")
    L.append("                HipDeg = hip, KneeDeg = knee, Asymmetry = asym")
    L.append("            };")
    L.append("        }")
    L.append("")
    for rig in rigs:
        n = ident(rig["id"])
        L.append("        public static readonly Rig %s = new Rig")
        L[-1] = L[-1] % (n,)
        L.append("        {")
        L.append('            Id = "%s", Sprite = "%s", HeightM = %sf,' % (rig["id"], rig["sprite"], rig["height_m"]))
        L.append("            Joints = new[]")
        L.append("            {")
        for j in rig["joints"]:
            L.append('                new Joint { Name = "%s", Parent = %d, X = %sf, Y = %sf },'
                     % (j["name"], j["parent"], j["x"], j["y"]))
        L.append("            },")
        g = rig.get("gait", {})
        L.append("            Gait = G(%sf, %sf, %sf, %sf, %sf, %sf, %sf, %sf, %sf, %sf, %sf, %sf)"
                 % (g.get("bob_m", 0.05), g.get("sway_m", 0.03), g.get("root_tilt_deg", 2.0),
                    g.get("spine_deg", 1.5), g.get("chest_deg", 2.0), g.get("head_deg", 3.0),
                    g.get("head_lag", 0.3), g.get("arm_swing_deg", 12.0), g.get("elbow_deg", 8.0),
                    g.get("hip_deg", 2.0), g.get("knee_deg", 3.0), g.get("asymmetry", 0.8)))
        L.append("        };")
        L.append("")
    L.append("        public static readonly Rig[] All = { %s };"
             % ", ".join(ident(r["id"]) for r in rigs))
    L.append("")
    L.append("        public static Rig Of(string id)")
    L.append("        {")
    L.append("            for (int i = 0; i < All.Length; i++)")
    L.append("                if (All[i].Id == id) return All[i];")
    L.append("            return null;")
    L.append("        }")
    L.append("    }")
    L.append("}")
    return "\n".join(L) + "\n"


def main():
    rigs = load()
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(emit(rigs))
    print("wrote %s (%d rigs: %s)" % (OUT, len(rigs), ", ".join(r["id"] for r in rigs)))


if __name__ == "__main__":
    main()
